/*
 * REGENERATE src/components/meridian/brand-glyphs.gen.ts FROM PUBLISHED BRAND ART.
 *
 *   bun run scripts/fetch-brand-glyphs.ts
 *
 * ── WHY THIS IS A SCRIPT AND NOT A HAND-MAINTAINED FILE ─────────────────
 * Because the alternative was measured and it failed twice on 2026-08-23.
 * Linear's mark was three straight strokes somebody drew freehand, and every
 * other "official" mark was a single monochrome silhouette lifted from
 * simple-icons, so Slack, a four-colour logo, shipped as one flat shape.
 *
 * Path data cannot be reviewed by eye. Nobody reads 2,000 characters of bezier
 * and notices it is the wrong company. So it is fetched from the publisher and
 * converted mechanically, and the output is generated rather than edited. The
 * founder's instruction was "do not invent that, use the original thing", and a
 * script is the only version of that promise anyone can check.
 *
 * ── SOURCES ─────────────────────────────────────────────────────────────
 * gilbarbara/logos first: it publishes true multi-path multi-fill brand SVGs,
 * which is the whole point. simple-icons second, for marks it does not carry;
 * those are monochrome by design, which is correct for brands whose mark IS
 * monochrome and wrong for anything else, so nothing colourful falls back to it.
 */

